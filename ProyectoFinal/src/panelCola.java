    /**
     * Configura el modelo para soportar imágenes y ajusta el tamaño de las celdas
     */
    private void inicializarModeloCola() {
        // Reemplaza el modelo por defecto por uno que reconozca imágenes
        modeloTablaCola = new DefaultTableModel(
            new Object [][] {},
            new String [] {"Imagen", "Título", "Artista"}
        ) {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                // Indicar a Java que la primera columna (0) contiene una Imagen
                if (columnIndex == 0) {
                    return ImageIcon.class; 
                }
                return String.class;
            }
            
            @Override
            public boolean isCellEditable(int rowIndex, int columnIndex) {
                return false; // Ninguna celda se puede editar
            }
        };
        
        tablaCola.setModel(modeloTablaCola);
        
        // Hacer las filas más anchas para que la portada se vea bien
        tablaCola.setRowHeight(60); 
    }
    
    private void estilizarEncabezado() {
        javax.swing.table.DefaultTableCellRenderer renderEncabezado = new javax.swing.table.DefaultTableCellRenderer();
        renderEncabezado.setBackground(new java.awt.Color(0, 51, 102));
        renderEncabezado.setForeground(java.awt.Color.WHITE);
        renderEncabezado.setFont(new java.awt.Font("Segoe UI", java.awt.Font.BOLD, 12));
        renderEncabezado.setHorizontalAlignment(javax.swing.JLabel.CENTER);

        for (int i = 0; i < tablaCola.getModel().getColumnCount(); i++) {
            tablaCola.getColumnModel().getColumn(i).setHeaderRenderer(renderEncabezado);
        }
        
        tablaCola.setBackground(new java.awt.Color(0, 51, 102));
        tablaCola.setForeground(java.awt.Color.WHITE);
        jScrollPane2.getViewport().setBackground(new java.awt.Color(0, 51, 102));
    }

    /**
     * Sincroniza los componentes visuales del panel.
     * Ya no necesitamos pasar cancionActual, solo llenamos la tabla.
     */
    public void actualizarPanel(ColaReproduccion cola) {
        this.colaGlobal = cola;
        // Limpiar filas previas
        modeloTablaCola.setRowCount(0);
        
        Cancion actualCola = cola.getFrente();
        while (actualCola != null) {
            ImageIcon miniatura = null;
            
            // Procesamos la imagen para hacerla miniatura (50x50)
            java.io.File archivoImagen = new java.io.File(actualCola.getRutaImagen());
            if (archivoImagen.exists()) {
                ImageIcon iconoOriginal = new ImageIcon(actualCola.getRutaImagen());
                java.awt.Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(50, 50, java.awt.Image.SCALE_SMOOTH);
                miniatura = new ImageIcon(imagenEscalada);
            }
            
            // Insertamos la miniatura junto al texto
            Object[] fila = {miniatura, actualCola.getTitulo(), actualCola.getArtista()};
            modeloTablaCola.addRow(fila);
            
            actualCola = actualCola.getSiguiente();
        }
    }

    
