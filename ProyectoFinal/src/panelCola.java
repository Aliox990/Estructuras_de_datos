    private void btnQuitarColaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnQuitarColaActionPerformed
        // Obtener el índice de la fila que el usuario seleccionó
        int filaSeleccionada = tablaCola.getSelectedRow();

        if (filaSeleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecciona una canción de la tabla para quitarla.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // Extraer el texto del título
        String tituloSeleccionado = tablaCola.getValueAt(filaSeleccionada, 1).toString();

        // Ejecutar la desconexión de apuntadores en la memoria RAM
        boolean exito = colaGlobal.eliminarPorTitulo(tituloSeleccionado);

        if (exito) {
            // Refresca la interfaz visual pasándole la cola ya modificada
            actualizarPanel(colaGlobal);
        }
    }//GEN-LAST:event_btnQuitarColaActionPerformed


